ORDER = ["ifma", "avx512", "avx2", "scalar"]
MACRO = {"ifma": "Ifma", "avx512": "AvxVn", "avx2": "AvxTwo", "scalar": "Scalar"}
LABEL = {"ifma": "IFMA", "avx512": "AVX-512", "avx2": "AVX2", "scalar": "scalar"}
RELATION = {"h-u": "$\\Relu$", "h-exact": "$\\Relex$", "h-fips": "$\\Relfips$"}
ALLOC_ORDER = ["16C32T", "8C16T", "1T", "all"]


def preferred_allocation(cells):
    for allocation in ALLOC_ORDER:
        if allocation != "all" and any(c["allocation"] == allocation for c in cells):
            return allocation
    return cells[0]["allocation"]


def load_cells(directory):
    cells = []
    for path in sorted((directory / "raw").glob("*.json")):
        try:
            cell = read_json(path)
        except (OSError, json.JSONDecodeError):
            continue
        if cell.get("times_ms") or cell.get("verify_uncached_ms"):
            cells.append(cell)
    return cells


def skipped_configs(directory):
    path = directory / "skipped.json"
    if not path.exists():
        return {}
    try:
        entries = read_json(path)
    except (OSError, json.JSONDecodeError):
        return {}
    result = {}
    for entry in entries:
        if entry.get("kind") != "configuration":
            continue
        reason = entry.get("reason", "")
        if "avx512ifma" in reason:
            result[entry["name"]] = "n/a (CPU without AVX-512IFMA)"
        elif "avx512f" in reason:
            result[entry["name"]] = "n/a (CPU without AVX-512)"
        elif "avx2" in reason:
            result[entry["name"]] = "n/a (CPU below x86-64-v3)"
        else:
            result[entry["name"]] = "n/a (" + reason + ")"
    return result


def by_key(cells, system="ours"):
    table = {}
    for cell in cells:
        if cell.get("system") != system:
            continue
        key = (cell["tag"], cell["config"], cell["allocation"], cell["n"], cell["relation"])
        if key not in table or cell.get("reps", 0) > table[key].get("reps", 0):
            table[key] = cell
    return table


def headline_cells(cells):
    ours = [c for c in cells if c.get("system") == "ours"]
    tagged = [
        c
        for c in ours
        if (
            str(c.get("tag", "")).startswith("headline")
            or str(c.get("tag", "")) == "relations"
        )
        and not c.get("tag", "").endswith("1t")
    ]
    if not tagged:
        tagged = [c for c in ours if str(c.get("tag", "")).startswith("quick-ours") and not c.get("tag", "").endswith("1t")]
    if not tagged:
        tagged = ours
    return tagged


def fmt_seconds(ms):
    return f"{ms / 1000:.2f}"


def fmt_ms(ms):
    if ms is None:
        return "--"
    if ms < 100:
        return f"{ms:.1f}"
    return f"{ms:.0f}"


def fmt_bytes_per_sig(cell):
    if not cell.get("aggregate_bytes"):
        return "--"
    return f"{cell['aggregate_bytes'] / cell['n']:.1f}"


def header(directory, commit, machine):
    return (
        f"% Generated by artifact/scripts/gen_tables.py\n"
        f"% Results: {directory}\n"
        f"% Commit: {commit}\n"
        f"% Machine: {machine}\n"
        f"% Date: {utc_stamp()}\n"
    )


def table_begin(label, caption, note, colspec, header_rows=1):
    return (
        "\\begin{table}[t]\n\\centering\n"
        "\\begin{talltblr}[\n"
        f"  caption = {{{caption}}},\n"
        f"  label = {{{label}}},\n"
        f"  remark{{Note}} = {{{note}}},\n"
        "]{\n"
        f"  width = \\linewidth,\n  colspec = {{{colspec}}},\n"
        "  colsep = 4pt,\n"
        f"  row{{1{(',' + str(header_rows)) if header_rows > 1 else ''}}} = {{font=\\bfseries}},\n"
        "  rows = {valign=m},\n"
        f"  hline{{1,{header_rows + 1},Z}} = {{1pt}},\n"
        "}\n"
    )


def e2e_table(cells, directory, commit, machine, skipped):
    data = headline_cells(cells)
    if not data:
        return "% no headline data\n"
    n = max(c["n"] for c in data)
    data = [c for c in data if c["n"] == n]
    relations = []
    for c in data:
        if c["relation"] not in relations and c["relation"] in ("h-u", "h-exact", "h-fips"):
            relations.append(c["relation"])
    allocs = [a for a in ALLOC_ORDER if any(c["allocation"] == a for c in data) and a != "all"]
    if not allocs:
        allocs = ["8C16T"]
    verify_alloc = "16C32T" if "16C32T" in allocs else allocs[0]
    lookup = {
        (c["config"], c["allocation"], c["relation"]): c for c in data
    }
    cols = "Q[l] Q[l] " + " ".join("X[r]" for _ in allocs) + " X[1.3,r]"
    out = header(directory, commit, machine)
    out += table_begin(
        "tab:ae-e2e",
        f"Mode~A at $N={f'{n:,}'.replace(',', '{,}')}$, medians of the measured runs (measured on {machine}).",
        "Prove in seconds. Verify on " + verify_alloc + ", uncached / cached keys, in ms. "
        "Values are medians; the appendix gives the full ranges.",
        cols,
        1,
    )
    out += "Build & Rel. & " + " & ".join(allocs) + " & Verify \\\\\n"
    for config in ORDER:
        for relation in relations:
            row = [LABEL.get(config, config), RELATION.get(relation, relation)]
            any_value = False
            for allocation in allocs:
                cell = lookup.get((config, allocation, relation))
                if cell and cell.get("times_ms"):
                    row.append(fmt_seconds(median(cell["times_ms"])))
                    any_value = True
                else:
                    row.append("--")
            cell = lookup.get((config, verify_alloc, relation))
            if cell and cell.get("verify_uncached_ms"):
                row.append(
                    fmt_ms(median(cell["verify_uncached_ms"]))
                    + " / "
                    + (fmt_ms(median(cell["verify_cached_ms"])) if cell.get("verify_cached_ms") else "--")
                )
                any_value = True
            else:
                row.append("--")
            if any_value:
                out += " & ".join(row) + " \\\\\n"
    for config in ORDER:
        if config in skipped and not any(c["config"] == config for c in data):
            row = [LABEL.get(config, config), "$\\Relu$"]
            row += [skipped[config]] + ["--"] * (len(allocs) - 1)
            row.append("--")
            out += " & ".join(row) + " \\\\\n"
    out += "\\end{talltblr}\n\\end{table}\n"
    return out


def ablation_table(cells, directory, commit, machine, skipped):
    data = headline_cells(cells)
    abl = [c for c in cells if c.get("system") == "ours" and "ablation" in str(c.get("tag", ""))]
    if not data and not abl:
        return "% no ablation data\n"
    out = header(directory, commit, machine)
    out += table_begin(
        "tab:ae-ablation",
        "ISA ladder and control ablations" + (f" (measured on {machine})." if machine else "."),
        "Prove in ms; in parentheses the change against the defaults of the same series. "
        "Cells without data are omitted.",
        "X[2.6,l] X[1,r] X[1,r] X[1,r] X[1,r]",
    )
    out += "Setting & " + " & ".join(LABEL[c] for c in ORDER) + " \\\\\n"
    # ISA ladder from the headline cells.
    if data:
        n = max(c["n"] for c in data)
        allocation = preferred_allocation(data)
        for config in ORDER:
            matches = [
                c for c in data
                if c["config"] == config and c["n"] == n and c["allocation"] == allocation
                and c["relation"] == "h-u" and c.get("times_ms")
            ]
            if matches:
                value = f"{median(matches[0]['times_ms']):.0f}"
                row = [f"{LABEL.get(config, config)} (ISA ladder)"]
                row += [value if c == config else "--" for c in ORDER]
                out += " & ".join(row) + " \\\\\n"
            elif config in skipped:
                row = [f"{LABEL.get(config, config)} (ISA ladder)"]
                row += [skipped[config] if c == config else "--" for c in ORDER]
                out += " & ".join(row) + " \\\\\n"
    # Knob ablations, with the defaults of the same series.
    defaults = {}
    for config in ("ifma", "avx2"):
        matches = [
            c for c in abl
            if c["config"] == config and c.get("arm") == "defaults" and c.get("times_ms")
        ]
        if matches:
            defaults[config] = median(matches[0]["times_ms"])
    arms = sorted(
        {
            c.get("arm")
            for c in abl
            if c.get("arm") and c.get("arm") != "defaults"
        }
    )
    for arm in arms:
        row = [arm.replace("-", " ")]
        for config in ORDER:
            matches = [
                c for c in abl
                if c["config"] == config and c.get("arm") == arm and c.get("times_ms")
            ]
            if matches:
                value = median(matches[0]["times_ms"])
                delta = value - defaults.get(config, value)
                row.append(f"{value:.0f} ({delta:+.0f})")
            else:
                row.append("--")
        out += " & ".join(row) + " \\\\\n"
    out += "\\end{talltblr}\n\\end{table}\n"
    return out


def scaling_table(cells, directory, commit, machine):
    ours = [
        c for c in cells
        if c.get("system") == "ours" and c["relation"] == "h-u" and c.get("times_ms")
        and ("scaling" in str(c.get("tag", "")) or "headline" in str(c.get("tag", "")) or "quick-ours" in str(c.get("tag", "")))
    ]
    if not ours:
        return "% no scaling data\n"
    sizes = sorted({c["n"] for c in ours})
    configs = [c for c in ORDER if any(x["config"] == c for x in ours)]
    allocation = preferred_allocation(ours)
    out = header(directory, commit, machine)
    out += table_begin(
        "tab:ae-scaling",
        f"Scaling of mode~A under $\\Relu$ (measured on {machine}).",
        "Prove in seconds on " + allocation + "; B/sig is the aggregate size per signature.",
        "Q[r] " + " ".join("Q[r]" for _ in configs) + " Q[r]",
    )
    out += "$N$ & " + " & ".join(LABEL.get(c, c) for c in configs) + " & B/sig \\\\\n"
    for n in sizes:
        row = [f"$2^{{{n.bit_length() - 1}}}$" if n & (n - 1) == 0 else f"{n:,}"]
        bps = "--"
        for config in configs:
            matches = [
                c for c in ours
                if c["config"] == config and c["n"] == n and c["allocation"] == allocation
            ]
            if matches:
                row.append(fmt_seconds(median(matches[0]["times_ms"])))
                bps = fmt_bytes_per_sig(matches[0])
            else:
                row.append("--")
        row.append(bps)
        out += " & ".join(row) + " \\\\\n"
    out += "\\end{talltblr}\n\\end{table}\n"
    return out


def bytes_table(cells, directory, commit, machine):
    ours = [
        c for c in cells
        if c.get("system") == "ours" and c["relation"] == "h-u" and c.get("aggregate_bytes")
    ]
    if not ours:
        return "% no byte data\n"
    sizes = sorted({c["n"] for c in ours})
    out = header(directory, commit, machine)
    out += table_begin(
        "tab:ae-bytes",
        "Aggregate size under $\\Relu$" + (f" (measured on {machine})." if machine else "."),
        "Bytes and bytes per signature. Public hashes are 32 bytes per signature.",
        "Q[r] Q[r] Q[r]",
    )
    out += "$N$ & bytes & B/sig \\\\\n"
    for n in sizes:
        matches = [c for c in ours if c["n"] == n]
        if not matches:
            continue
        cell = matches[0]
        out += (
            f"{n:,} & {cell['aggregate_bytes']:,} & "
            f"{fmt_bytes_per_sig(cell)} \\\\\n"
        )
    out += "\\end{talltblr}\n\\end{table}\n"
    return out


def baselines_table(cells, directory, commit, machine):
    candidates = [
        c for c in cells
        if c.get("system") == "ours" and c["relation"] == "h-u" and c.get("times_ms")
    ]
    ours_by_key = {}
    for cell in candidates:
        key = (cell["config"], cell["allocation"])
        if key not in ours_by_key or cell.get("reps", 0) > ours_by_key[key].get("reps", 0):
            ours_by_key[key] = cell
    ours = list(ours_by_key.values())
    def dedup(items, key):
        chosen = {}
        for item in items:
            k = key(item)
            if k not in chosen or item.get("reps", 0) > chosen[k].get("reps", 0):
                chosen[k] = item
        return list(chosen.values())

    aerie = dedup(
        [c for c in cells if c.get("system") == "aerie"],
        lambda c: (c.get("tag"), c["allocation"], c["n"]),
    )
    native = dedup(
        [c for c in cells if c.get("system") == "native"],
        lambda c: (c["allocation"], c["n"]),
    )
    if not ours and not aerie and not native:
        return "% no baseline data\n"
    out = header(directory, commit, machine)
    out += table_begin(
        "tab:ae-baselines",
        f"Baselines (measured on {machine}).",
        "Prove in s; verify in ms, uncached / cached keys. --: not measured.",
        "X[2.3,l] X[1.2,l] X[1,r] X[1.5,r] X[1,r]",
    )
    out += "System & Alloc. & Prove & Verify & B/sig \\\\\n"
    allocs = [a for a in ALLOC_ORDER if a != "all"]
    for allocation in allocs:
        for cell in native:
            if cell["allocation"] != allocation:
                continue
            native_verify = fmt_ms(median(cell["verify_uncached_ms"]))
            if cell.get("verify_cached_ms"):
                native_verify += " / " + fmt_ms(median(cell["verify_cached_ms"]))
            out += (
                f"native, AVX2 & {allocation} & -- & "
                f"{native_verify} & 2420 \\\\\n"
            )
        for cell in aerie:
            if cell["allocation"] != allocation:
                continue
            verify = median(cell["verify_uncached_ms"]) if cell.get("verify_uncached_ms") else None
            label = "Aerie (AVX2)" if cell.get("tag") == "aerie-avx2" else "Aerie"
            out += (
                f"{label} & {allocation} & {fmt_seconds(median(cell['times_ms']))} & "
                f"{fmt_ms(verify)} & "
                f"{(cell['aggregate_bytes'] / cell['n']):.1f} \\\\\n"
            )
        for config in ORDER:
            matches = [
                c for c in ours
                if c["config"] == config and c["allocation"] == allocation
            ]
            if not matches:
                continue
            cell = matches[0]
            verify = fmt_ms(median(cell["verify_uncached_ms"])) if cell.get("verify_uncached_ms") else "--"
            cached = fmt_ms(median(cell["verify_cached_ms"])) if cell.get("verify_cached_ms") else "--"
            out += (
                f"ours, {LABEL.get(config, config)} & {allocation} & "
                f"{fmt_seconds(median(cell['times_ms']))} & {verify} / {cached} & "
                f"{fmt_bytes_per_sig(cell)} \\\\\n"
            )
    out += "\\end{talltblr}\n\\end{table}\n"
    return out


def numbers(cells, directory, commit, machine):
    data = [c for c in headline_cells(cells) if c["relation"] == "h-u" and c.get("times_ms")]
    lines = [header(directory, commit, machine)]
    if not data:
        return "".join(lines) + "% no headline data\n"
    n = max(c["n"] for c in data)
    data = [c for c in data if c["n"] == n]
    allocation = preferred_allocation(data)
    values = {}
    for config in ORDER:
        matches = [
            c for c in data if c["config"] == config and c["allocation"] == allocation
        ]
        if not matches:
            continue
        cell = matches[0]
        values[f"Prove{MACRO[config]}"] = fmt_seconds(median(cell["times_ms"]))
        if cell.get("verify_uncached_ms"):
            values[f"Verify{MACRO[config]}Uncached"] = fmt_ms(median(cell["verify_uncached_ms"]))
        if cell.get("verify_cached_ms"):
            values[f"Verify{MACRO[config]}Cached"] = fmt_ms(median(cell["verify_cached_ms"]))
        if cell.get("aggregate_bytes"):
            values[f"BytesPerSig{MACRO[config]}"] = fmt_bytes_per_sig(cell)
            values["AggregateBytes"] = f"{cell['aggregate_bytes']:,}".replace(",", "{,}")
    if "ProveIfma" in values and "ProveAvxTwo" in values:
        try:
            values["GainIfmaOverAvxTwo"] = f"{float(values['ProveAvxTwo']) / float(values['ProveIfma']):.1f}"
            values["GainIfmaOverScalar"] = (
                f"{float(values['ProveScalar']) / float(values['ProveIfma']):.1f}"
                if "ProveScalar" in values else None
            )
        except ValueError:
            pass
    for name, value in values.items():
        if value:
            lines.append(f"\\newcommand{{\\{name}}}{{{value}}}\n")
    return "".join(lines)


def claims_csv(cells, directory):
    rows = []
    for cell in cells:
        if cell.get("system") != "ours":
            continue
        prove = describe(cell.get("times_ms") or [])
        uncached = describe(cell.get("verify_uncached_ms") or [])
        cached = describe(cell.get("verify_cached_ms") or [])
        rows.append(
            {
                "run_id": cell["run_id"],
                "config": cell["config"],
                "allocation": cell["allocation"],
                "n": cell["n"],
                "relation": cell["relation"],
                "prove_median_ms": prove["median"] if prove else "",
                "verify_uncached_median_ms": uncached["median"] if uncached else "",
                "verify_cached_median_ms": cached["median"] if cached else "",
                "aggregate_bytes": cell.get("aggregate_bytes", ""),
                "aggregate_sha256": cell.get("aggregate_sha256", ""),
            }
        )
    path = directory / "claims-measured.csv"
    if rows:
        with open(path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", help="results directory (default: LATEST)")
    args = parser.parse_args()
    directory = result_dir(args.results)
    cells = load_cells(directory)
    skipped = skipped_configs(directory)
    commit = next(
        (c.get("commit") for c in cells if c.get("system") == "ours" and c.get("commit")),
        "unknown",
    )
    machine = next((c.get("machine") for c in cells if c.get("machine")), "unknown")
    TABLES.mkdir(parents=True, exist_ok=True)
    outputs = {
        "tab-e2e.tex": e2e_table(cells, directory, commit, machine, skipped),
        "tab-ablation.tex": ablation_table(cells, directory, commit, machine, skipped),
        "tab-scaling.tex": scaling_table(cells, directory, commit, machine),
        "tab-bytes.tex": bytes_table(cells, directory, commit, machine),
        "tab-baselines.tex": baselines_table(cells, directory, commit, machine),
        "numbers.tex": numbers(cells, directory, commit, machine),
    }
    for name, text in outputs.items():
        (TABLES / name).write_text(text, encoding="utf-8")
    copy = directory / "paper-tables"
    copy.mkdir(exist_ok=True)
    for name, text in outputs.items():
        (copy / name).write_text(text, encoding="utf-8")
    claims_csv(cells, directory)
    print(f"tables: {TABLES}")
    for name in outputs:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
